import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { lookup, renderCss, resolveValue, toCssVariables, TokenError } from "../src/design/tokens.ts";

const dir = resolve(import.meta.dirname, "..");
const json = JSON.parse(readFileSync(resolve(dir, "src/design/design-tokens.json"), "utf8"));

describe("D9 design tokens", () => {
  it("resolves semantic and component aliases to primitive values", () => {
    expect(resolveValue(json, lookup(json, "component.button.primary.background").value)).toBe("#3864ed");
    expect(resolveValue(json, lookup(json, "semantic.color.surface.canvas").value)).toBe("#f7f8fb");
  });
  it("every semantic/component token resolves (no missing or circular alias)", () => {
    const vars = toCssVariables(json);
    expect(vars.length).toBeGreaterThan(150);
    expect(vars.some(([, v]) => v.includes("{"))).toBe(false);
  });
  it("detects missing and circular aliases", () => {
    const bad = { a: { type: "color", value: "{b}" }, b: { type: "color", value: "{a}" }, c: { type: "color", value: "{nope.x}" } };
    expect(() => resolveValue(bad, "{a}")).toThrow(TokenError);
    expect(() => resolveValue(bad, "{c}")).toThrow(/Missing token/);
  });
  it("checked-in tokens.css matches the JSON (run `pnpm tokens` after changing it)", () => {
    const css = readFileSync(resolve(dir, "src/app/tokens.css"), "utf8");
    expect(css).toBe(renderCss(json, `Generated by scripts/build-tokens.ts from Peerly design-tokens.json v${json.metadata.version}. Do not edit.`));
  });
  it("no generated font size below 12px", () => {
    for (const [k, v] of toCssVariables(json)) if (k.endsWith("-size") && v.endsWith("px") && k.includes("typography")) expect(parseInt(v)).toBeGreaterThanOrEqual(12);
  });
});
