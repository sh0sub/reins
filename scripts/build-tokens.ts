/** pnpm tokens -> regenerates apps/web/src/app/tokens.css from the pinned Peerly token JSON. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { renderCss } from "../apps/web/src/design/tokens.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const json = JSON.parse(readFileSync(resolve(root, "apps/web/src/design/design-tokens.json"), "utf8"));
const css = renderCss(json, `Generated by scripts/build-tokens.ts from Peerly design-tokens.json v${json.metadata.version}. Do not edit.`);
writeFileSync(resolve(root, "apps/web/src/app/tokens.css"), css);
console.log("wrote apps/web/src/app/tokens.css");
